def grid(s):
    rows = [r for r in s.strip('\n').split('\n')]
    return [r.ljust(32, '.')[:32] for r in rows]
out = Image.new('RGBA', (32 * len(SPR), 32), (0, 0, 0, 0))
for i, (k, s) in enumerate(SPR.items()):
    g = grid(s); oy = 32 - len(g)
    if k == 'kongal': g = [r[::-1] for r in g]   # 다른 동물처럼 오른쪽을 봐요
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch != '.': out.putpixel((i * 32 + x, oy + y), PAL[ch] + (255,))
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'public', 'art', 'cast_animals.png')
