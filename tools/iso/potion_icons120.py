def draw16(idx, pid, color):
    shape, cork, sym, symc, extra, sparkle, dy = DESIGN[pid]
    shape = shape or COL_SHAPE[idx % 10]
    g, cx, cy = SHAPES[shape]
    g = grid(g)
    main = color
    pal = {'o': OUT, 'c': CORK[cork], 'g': GLASS, 'L': add(main, 45), 'M': main,
           'D': add(main, -40), 'H': add(main, -50), 'y': (255, 215, 90)}
    if pid == 'pt120': pal['D'] = (170, 205, 245); pal['L'] = (255, 255, 255)
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch in pal: im.putpixel((x, y), pal[ch] + (255,))
    if symc is None: symc = WHITE if lum(main) < 205 else add(main, -110)
    spal = dict(extra); spal['X'] = symc
    m = grid(SYM[sym]); h, w = len(m), max(len(r) for r in m)
    x0 = int(cx - (w - 1) / 2); y0 = int(cy - (h - 1) / 2) + dy
    for y, row in enumerate(m):
        for x, ch in enumerate(row):
            if ch in spal:
                X, Y = x0 + x, y0 + y
                p = im.getpixel((X, Y))
                if p[3] and p[:3] not in (OUT,): im.putpixel((X, Y), spal[ch] + (255,))
    if pid == 'pt120':   # 코르크 위 눈 모자 + 은은한 빛 테두리
        for x in range(6, 10): im.putpixel((x, 0), (250, 252, 255, 255))
        im.putpixel((5, 1), (250, 252, 255, 255)); im.putpixel((10, 1), (250, 252, 255, 255))
    return im, sparkle

def glow(im, col, a):   # 외곽 투명 칸 중 불투명 칸에 4방향으로 닿는 곳에 반투명 빛
    out = im.copy(); W, H = im.size
    for y in range(H):
        for x in range(W):
            if im.getpixel((x, y))[3]: continue
            if any(0 <= x + dx < W and 0 <= y + dy < H and im.getpixel((x + dx, y + dy))[3] == 255
                   for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                out.putpixel((x, y), col + (a,))
    return out

def sparkles(im, level, gold=False):
    pts = {1: [(13, 2, 'plus'), (2, 4, 'dot')],
           2: [(13, 2, 'plus'), (2, 3, 'plus'), (15, 12, 'dot'), (0, 9, 'dot')]}[level]
    hi = (255, 255, 250, 255); arm = (255, 226, 122, 255) if gold else (190, 225, 255, 255)
    def put(x, y, c):
        if 0 <= x < 16 and 0 <= y < 16 and im.getpixel((x, y))[3] < 255: im.putpixel((x, y), c)
    for x, y, k in pts:
        put(x, y, hi)
        if k == 'plus':
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)): put(x + dx, y + dy, arm)
    return im

def load_rows():
    return json.load(open(SPEC, encoding='utf-8'))['potion']

def build():
    rows = load_rows(); assert len(rows) == 20
    small = Image.new('RGBA', (160, 32), (0, 0, 0, 0))
    for k, r in enumerate(rows):
        pid, color = r[0], hexc(r[4]); idx = 100 + k
        im, sp = draw16(idx, pid, color)
        if pid == 'pt120':
            im = sparkles(im, 2, gold=True)
        elif sp:
            im = sparkles(im, sp, gold=pid in ('pt119', 'pt118'))
        small.alpha_composite(im, ((k % 10) * 16, (k // 10) * 16))
    return small.resize((320, 64), Image.NEAREST), rows

def cjk_font(size):
    try:
        out = subprocess.run(['fc-list', ':lang=ko', 'file'], capture_output=True, text=True).stdout
        for line in out.splitlines():
            p = line.split(':')[0].strip()
            if p and 'unifont' not in p.lower(): return ImageFont.truetype(p, size)
    except Exception: pass
    return None

def on_bg(im, bg=(60, 58, 72)):
    b = Image.new('RGBA', im.size, bg + (255,)); b.alpha_composite(im); return b

def preview(d):
    os.makedirs(d, exist_ok=True)
    new, rows = build()
    new.save(os.path.join(d, 'potion_new20.png'))
    # 4배 + 이름
    font = cjk_font(14); cw, chh = 128, 128 + 22
    lbl = Image.new('RGBA', (cw * 10, chh * 2), (60, 58, 72, 255)); dr = ImageDraw.Draw(lbl)
    big = new.resize((1280, 256), Image.NEAREST)
    for k, r in enumerate(rows):
        c, rr = k % 10, k // 10
        lbl.alpha_composite(big.crop((c * 128, rr * 128, c * 128 + 128, rr * 128 + 128)), (c * cw, rr * chh))
        if font:
            t = f"{r[0][2:]} {r[1].replace(' 물약', '').replace('의', '')}"
            tw = dr.textlength(t, font=font)
            dr.text((c * cw + (cw - tw) / 2, rr * chh + 130), t, font=font, fill=(240, 240, 240))
    lbl.save(os.path.join(d, 'potion_new20_x4_lbl.png'))
    # 기존과 비교: 기존 마지막 4줄 + 새 2줄, 3배
    old = Image.open(SHEET).convert('RGBA')
    comb = Image.new('RGBA', (320, 128 + 4 + 64), (0, 0, 0, 0))
    comb.alpha_composite(old.crop((0, 192, 320, 320)), (0, 0)); comb.alpha_composite(new, (0, 132))
    c3 = on_bg(comb).resize((960, comb.height * 3), Image.NEAREST)
    ImageDraw.Draw(c3).rectangle([0, 128 * 3, 960, 132 * 3 - 1], fill=(230, 120, 120, 255))
    c3.save(os.path.join(d, 'potion_compare.png'))
    print('wrote', d)

def apply():
    new, _ = build()
    old = Image.open(SHEET).convert('RGBA')
    out = Image.new('RGBA', (320, 384), (0, 0, 0, 0))
    out.alpha_composite(old.crop((0, 0, 320, 320)), (0, 0)); out.alpha_composite(new, (0, 320))
    out.save(SHEET); print('wrote', SHEET, out.size)

if __name__ == '__main__':
    ap = argparse.ArgumentParser()
