def mini(shape):
    rows,b,a=shape; N=8; out=[]
    for y in range(N):
        r=''
        for x in range(N):
            # 12 → 8: 칸마다 원래 3/2 칸을 보고, 눈(e)은 남기고, 아니면 많은 쪽
            xs=[int(x*1.5),min(11,int(x*1.5+1))]; ys=[int(y*1.5),min(11,int(y*1.5+1))]
            cs=[rows[yy][xx] for yy in ys for xx in xs]
            r+='e' if 'e' in cs and cs.count('.')<2 else ('2' if cs.count('2')>=2 else ('1' if sum(c!='.' for c in cs)>=2 else '.'))
        out.append(r+'....')
    return (out+['............']*4,b,a)
